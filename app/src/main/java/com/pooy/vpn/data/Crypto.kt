package com.pooy.vpn.data

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.security.keystore.KeyPermanentlyInvalidatedException
import java.security.KeyStore
import java.security.UnrecoverableKeyException
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Encrypts/decrypts opaque blobs. Implemented by [Crypto] (Keystore) and, in tests, by [AesGcmBlobCipher] with a software key. */
interface BlobCipher {
    fun encrypt(plain: ByteArray): ByteArray
    fun decrypt(blob: ByteArray): ByteArray
}

/**
 * AES-256-GCM. Blob layout (unchanged from earlier versions, so existing files stay readable):
 * 12-byte IV || ciphertext+16-byte tag. The IV is generated by the provider's SecureRandom on every
 * encrypt (the Keystore refuses caller-supplied IVs for encryption), so an IV is never reused.
 */
class AesGcmBlobCipher(private val key: () -> SecretKey) : BlobCipher {
    override fun encrypt(plain: ByteArray): ByteArray {
        val c = Cipher.getInstance(TRANSFORMATION)
        c.init(Cipher.ENCRYPT_MODE, key())
        val iv = c.iv
        check(iv != null && iv.size == IV_LEN) { "Unexpected IV length" }
        return iv + c.doFinal(plain)
    }

    override fun decrypt(blob: ByteArray): ByteArray {
        require(blob.size >= IV_LEN + TAG_BYTES) { "Blob too short" }
        val c = Cipher.getInstance(TRANSFORMATION)
        c.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BITS, blob, 0, IV_LEN))
        return c.doFinal(blob, IV_LEN, blob.size - IV_LEN)
    }

    companion object {
        const val IV_LEN = 12
        const val TAG_BITS = 128
        const val TAG_BYTES = TAG_BITS / 8
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
    }
}

private const val ALIAS = "pooy_store_key_v1"
private const val PROVIDER = "AndroidKeyStore"

/** Non-exportable AES-256 key held in the Android Keystore; created on first use. */
private fun keystoreKey(): SecretKey {
    val ks = KeyStore.getInstance(PROVIDER).apply { load(null) }
    (ks.getKey(ALIAS, null) as? SecretKey)?.let { return it }
    val gen = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
    gen.init(
        KeyGenParameterSpec.Builder(ALIAS, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setRandomizedEncryptionRequired(true)
            .build(),
    )
    return gen.generateKey()
}

object Crypto : BlobCipher {
    private val impl = AesGcmBlobCipher { keystoreKey() }

    /**
     * If the Keystore key is permanently unusable (invalidated or unrecoverable), existing ciphertext is already
     * lost, and without a new key the user could never save again. Only then is the key replaced, once. Transient
     * Keystore errors are NOT treated this way (they propagate), because replacing a healthy key would destroy data.
     * Decryption never replaces the key.
     */
    @Synchronized
    override fun encrypt(plain: ByteArray): ByteArray =
        try {
            impl.encrypt(plain)
        } catch (e: KeyPermanentlyInvalidatedException) {
            resetKey(); impl.encrypt(plain)
        } catch (e: UnrecoverableKeyException) {
            resetKey(); impl.encrypt(plain)
        }

    override fun decrypt(blob: ByteArray): ByteArray = impl.decrypt(blob)

    private fun resetKey() {
        KeyStore.getInstance(PROVIDER).apply { load(null) }.deleteEntry(ALIAS)
    }
}
